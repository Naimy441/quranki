import { readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url));
const AUDIO_DIRECTORY = join(ROOT, '..', '..', 'assets', 'audio', 'word-pronunciations');
const OUTPUT = join(ROOT, '..', '..', 'src', 'data', 'word-pronunciation-assets.ts');
const files = (await readdir(AUDIO_DIRECTORY)).filter((file) => file.endsWith('.m4a')).sort();

const entries = files.map((file) => {
  const id = file.slice(0, -'.m4a'.length);
  return `  '${id}': require('../../assets/audio/word-pronunciations/${file}'),`;
});

await writeFile(
  OUTPUT,
  `// Generated by tools/pronunciation-recorder/generate-app-audio-map.mjs. Do not edit manually.\nexport const WORD_PRONUNCIATION_ASSETS = {\n${entries.join('\n')}\n} as const;\n`,
);
console.log(`Wrote ${files.length} pronunciation asset entries → ${OUTPUT}`);
